/** Lessons whose keywords appear in a recipe's title, tags, category or ingredient names. */
export function lessonsForRecipe(recipe: { title: string; tags: string[]; category: string; ingredients: { name: string }[] }): Lesson[] {
  const hay = [recipe.title, recipe.category, ...recipe.tags, ...recipe.ingredients.map((i) => i.name)].join(" ");
  return LESSONS.filter((l) => l.keywords.some((k) => hay.includes(k)));
}

